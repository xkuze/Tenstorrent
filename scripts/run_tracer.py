"""
TT-NN Tracer Script.

Extracts PyTorch operations from UNet model and generates:
- Operations list with counts
- Visual graph (SVG)
- TTNN code skeleton
- Unit tests for each operation
- Metadata JSON files

Usage:
    python scripts/run_tracer.py --phase all
    python scripts/run_tracer.py --phase ops      # Extract ops only
    python scripts/run_tracer.py --phase tests    # Generate tests only
    python scripts/run_tracer.py --phase codegen  # Generate code only
    python scripts/run_tracer.py --phase metadata # Generate metadata only

Output:
    - generated/tracer/graphs/unet_traced_graph.svg
    - generated/tracer/codegen/unet_*.py
    - generated/tracer/metadata/unet_*.json
    - generated/tracer/tests/test_unet_ops.py
"""

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

# Add project root to path
sys.path.insert(0, str(Path(__file__).parent.parent))

import torch
import ttnn

from unet.model import UNetVGG19


def setup_output_dirs():
    """Create output directories if they don't exist."""
    base = Path(__file__).parent.parent / "generated" / "tracer"
    dirs = ["graphs", "codegen", "metadata", "tests"]
    for d in dirs:
        (base / d).mkdir(parents=True, exist_ok=True)
    return base


def trace_model():
    """Trace UNet model and return graph."""
    print("=== Tracing UNet Model ===")

    # Disable fast runtime mode for tracing
    ttnn.CONFIG.enable_fast_runtime_mode = False
    ttnn.torch_tracer.enable_tracing()

    # Load model
    checkpoint = Path(__file__).parent.parent / "unet/weights/best_model.ckpt"
    model = UNetVGG19.load_from_checkpoint(str(checkpoint))
    model.eval()
    print(f"Model loaded from {checkpoint}")

    # Create input tensor for tracing
    x = torch.randn(1, 3, 256, 256)
    input_tensor = ttnn.torch_tracer.create_input_tensor(x)
    print(f"Input shape: {x.shape}")

    # Run forward pass
    with torch.no_grad():
        output = model(input_tensor)

    print(f"Output shape: {output.shape}")

    # Get flattened graph
    graph = ttnn.torch_tracer.flatten_graph(output)
    print(f"Graph nodes: {len(graph.nodes)}")

    return graph, model


def extract_ops(graph, output_dir: Path):
    """Extract and save operations list."""
    print("\n=== Extracting Operations ===")

    ops = []
    for node in graph.nodes(data=True):
        node_data = node[1]
        if "op" in node_data:
            ops.append(node_data["op"])

    # Count operations
    op_counts = Counter(ops)
    total = sum(op_counts.values())

    # Save ops list
    ops_file = output_dir / "metadata" / "unet_ops_list.txt"
    with open(ops_file, "w") as f:
        f.write(f"UNet Operations (Total: {total})\n")
        f.write("=" * 40 + "\n\n")
        for op, count in sorted(op_counts.items(), key=lambda x: -x[1]):
            f.write(f"{op}: {count}\n")

    print(f"Operations saved to {ops_file}")
    print(f"Total operations: {total}")
    for op, count in sorted(op_counts.items(), key=lambda x: -x[1])[:5]:
        print(f"  {op}: {count}")

    return op_counts


def generate_graph(graph, output_dir: Path):
    """Generate visual graph SVG."""
    print("\n=== Generating Graph ===")

    try:
        from networkx.drawing.nx_agraph import to_agraph

        # Convert to graphviz
        A = to_agraph(graph)
        A.graph_attr["rankdir"] = "TB"
        A.node_attr["shape"] = "box"
        A.node_attr["fontsize"] = "10"

        svg_path = output_dir / "graphs" / "unet_traced_graph.svg"
        A.draw(svg_path, prog="dot", format="svg")
        print(f"Graph saved to {svg_path}")

    except ImportError:
        print("Warning: pygraphviz not installed, skipping graph generation")
        print("Install with: pip install pygraphviz")


def generate_codegen(graph, model, output_dir: Path):
    """Generate TTNN code skeleton."""
    print("\n=== Generating TTNN Code ===")

    tracer = ttnn.torch_tracer

    # Generate main codegen
    codegen_path = output_dir / "codegen" / "unet_ttnn_codegen.py"
    with open(codegen_path, "w") as f:
        f.write('"""\n')
        f.write("Auto-generated TTNN code skeleton for UNet.\n")
        f.write("Generated by TT-NN Tracer.\n")
        f.write('"""\n\n')
        f.write("import ttnn\n")
        f.write("import torch\n\n")
        f.write(tracer.codegen(graph))
    print(f"Codegen saved to {codegen_path}")

    # Generate submodules
    submodules_path = output_dir / "codegen" / "unet_submodules.py"
    with open(submodules_path, "w") as f:
        f.write('"""\n')
        f.write("Auto-generated TTNN submodules for UNet.\n")
        f.write("Generated by TT-NN Tracer.\n")
        f.write('"""\n\n')
        f.write("import ttnn\n\n")
        submodules_code = "\n\n".join(tracer.codegen_submodules(graph))
        f.write(submodules_code)
    print(f"Submodules saved to {submodules_path}")

    # Generate top-level module
    top_level_path = output_dir / "codegen" / "unet_top_level.py"
    with open(top_level_path, "w") as f:
        f.write('"""\n')
        f.write("Auto-generated top-level TTNN module for UNet.\n")
        f.write("Generated by TT-NN Tracer.\n")
        f.write('"""\n\n')
        f.write("import ttnn\n\n")
        f.write(tracer.codegen_top_level_module(graph))
    print(f"Top-level saved to {top_level_path}")


def generate_metadata(graph, output_dir: Path):
    """Generate metadata JSON files."""
    print("\n=== Generating Metadata ===")

    # Graph structure
    nodes = []
    edges = []

    for node_id, node_data in graph.nodes(data=True):
        node_info = {"id": str(node_id)}
        for key, value in node_data.items():
            if isinstance(value, (str, int, float, bool, type(None))):
                node_info[key] = value
            elif isinstance(value, (list, tuple)):
                node_info[key] = list(value)
            elif hasattr(value, "tolist"):
                node_info[key] = value.tolist()
            else:
                node_info[key] = str(value)
        nodes.append(node_info)

    for src, dst in graph.edges():
        edges.append({"source": str(src), "target": str(dst)})

    graph_structure = {
        "nodes": nodes,
        "edges": edges,
        "node_count": len(nodes),
        "edge_count": len(edges),
    }

    graph_path = output_dir / "metadata" / "unet_graph_structure.json"
    with open(graph_path, "w") as f:
        json.dump(graph_structure, f, indent=2, default=str)
    print(f"Graph structure saved to {graph_path}")

    # TTNN metadata with timing
    ttnn_metadata = {
        "model": "UNetVGG19",
        "input_shape": [1, 3, 256, 256],
        "operations": [],
    }

    for node_id, node_data in graph.nodes(data=True):
        if "op" in node_data:
            op_info = {
                "id": str(node_id),
                "op": node_data.get("op"),
                "shape": node_data.get("shape"),
                "dtype": str(node_data.get("dtype", "float32")),
                "time_ms": node_data.get("time_ms", 0),
            }
            ttnn_metadata["operations"].append(op_info)

    metadata_path = output_dir / "metadata" / "unet_ttnn_metadata.json"
    with open(metadata_path, "w") as f:
        json.dump(ttnn_metadata, f, indent=2, default=str)
    print(f"TTNN metadata saved to {metadata_path}")

    # Ops mapping (PyTorch -> TTNN)
    ops_mapping = {
        "supported": {
            "conv2d": {"ttnn": "ttnn.conv2d", "notes": "Direct equivalent"},
            "relu": {"ttnn": "ttnn.relu", "notes": "Direct equivalent"},
            "batch_norm": {"ttnn": "ttnn.batch_norm", "notes": "Direct equivalent"},
            "max_pool2d": {"ttnn": "ttnn.max_pool2d", "notes": "Direct equivalent"},
            "pad": {"ttnn": "ttnn.pad", "notes": "Direct equivalent"},
            "cat": {
                "ttnn": "ttnn.concat",
                "notes": "Use ttnn.concat for concatenation",
            },
            "randn": {
                "ttnn": "torch.randn + ttnn.from_torch",
                "notes": "Generate on host",
            },
        },
        "partial_support": {
            "interpolate": {
                "ttnn": "ttnn.upsample",
                "notes": "Use scale_factor=2 or transpose_conv2d for bilinear",
            },
            "flatten": {
                "ttnn": "ttnn.reshape",
                "notes": "Use ttnn.reshape(tensor, [batch, -1])",
            },
        },
        "unsupported": {},
    }

    mapping_path = output_dir / "metadata" / "unet_ttnn_ops_mapping.json"
    with open(mapping_path, "w") as f:
        json.dump(ops_mapping, f, indent=2)
    print(f"Ops mapping saved to {mapping_path}")


