def main():
    parser = argparse.ArgumentParser(description="TT-NN Tracer for UNet")
    parser.add_argument(
        "--phase",
        choices=["all", "ops", "tests", "codegen", "metadata"],
        default="all",
        help="Which phase to run",
    )
    args = parser.parse_args()

    # Setup output directories
    output_dir = setup_output_dirs()

    # Trace model
    graph, model = trace_model()

    if args.phase in ["all", "ops"]:
        extract_ops(graph, output_dir)
        generate_graph(graph, output_dir)

    if args.phase in ["all", "codegen"]:
        generate_codegen(graph, model, output_dir)

    if args.phase in ["all", "metadata"]:
        generate_metadata(graph, output_dir)

    if args.phase in ["all", "tests"]:
        generate_tests(graph, output_dir)

    print("\n=== Tracer Complete ===")
    print(f"Output directory: {output_dir}")


if __name__ == "__main__":
    main()
